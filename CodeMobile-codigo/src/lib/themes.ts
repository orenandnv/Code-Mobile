export const THEME_DEFINITIONS: ThemeDefinition[] = [
  {
    id: 'dark',
    label: 'Dark+',
    description: 'Tema padrão do VS Code',
    monacoName: 'code-dark-plus',
    data: { base: 'vs-dark', inherit: true, rules: darkRules, colors: darkColors },
  },
  {
    id: 'light',
    label: 'Light+',
    description: 'Tema claro padrão do VS Code',
    monacoName: 'code-light-plus',
    data: { base: 'vs', inherit: true, rules: lightRules, colors: lightColors },
  },
  {
    id: 'hc',
    label: 'Alto Contraste',
    description: 'High Contrast Black do VS Code',
    monacoName: 'code-hc-black',
    data: { base: 'hc-black', inherit: true, rules: hcRules, colors: hcColors },
  },
];

export function monacoThemeName(theme: Theme): string {
  return THEME_DEFINITIONS.find((definition) => definition.id === theme)?.monacoName ?? 'code-dark-plus';
}
